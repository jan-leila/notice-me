// Builds src/pkjs/config-page.js: the settings page (config/config-page.html) with the shared modules it uses
// from src/common inlined, so the phone can open it as a data: URI (CONTRACTS.md §9).
//
// The modules are wrapped in a tiny CommonJS shim (ids are the file names without `.js`; require('./x') resolves
// among the bundled modules only) and exposed as window.NoticeMe = {settings}.
//
// usage: node tools/build-config.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const COMMON = ['settings'];
const MODULES_MARKER = '<!--NOTICEME-MODULES-->';
const PARAMS_MARKER = '<!--PARAMS-->';

function fail(msg) {
  console.error('build-config: ' + msg);
  process.exit(1);
}

const missing = COMMON.filter(m => !fs.existsSync(path.join(root, 'src/common', m + '.js')));
if (missing.length) fail('missing ' + missing.map(m => 'src/common/' + m + '.js').join(', ') + ' (needed by the settings page)');

// every require must resolve inside the bundle (fail at build time, not on the phone)
for (const m of COMMON) {
  const src = fs.readFileSync(path.join(root, 'src/common', m + '.js'), 'utf8');
  for (const r of src.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)) {
    if (!COMMON.includes(r[1].replace(/^\.\//, '').replace(/\.js$/, ''))) fail('src/common/' + m + ".js: require('" + r[1] + "') is not bundled");
  }
}

// code inside a <script> element must not close it or open an HTML comment
const scriptSafe = js => js.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

const defs = COMMON.map(m => {
  const src = fs.readFileSync(path.join(root, 'src/common', m + '.js'), 'utf8');
  return 'defs[' + JSON.stringify(m) + '] = function (module, exports, require) {\n' + src + '\n};';
}).join('\n');

const bundle = [
  '<script>',
  '(function () {',
  '  var defs = {}, cache = {};',
  '  function load(id) {',
  "    id = String(id).replace(/^\\.\\//, '').replace(/\\.js$/, '');",
  "    if (!defs.hasOwnProperty(id)) throw new Error('module not bundled: ' + id);",
  '    if (cache.hasOwnProperty(id)) return cache[id].exports;',
  '    var module = { exports: {} };',
  '    cache[id] = module;',
  '    defs[id](module, module.exports, load);',
  '    return module.exports;',
  '  }',
  scriptSafe(defs),
  '  window.NoticeMe = {',
  COMMON.map(m => '    ' + m + ": load('" + m + "')").join(',\n'),
  '  };',
  '})();',
  '</script>',
].join('\n');

let html = fs.readFileSync(path.join(root, 'config/config-page.html'), 'utf8');
if (!html.includes(MODULES_MARKER)) fail('config/config-page.html has no ' + MODULES_MARKER + ' marker');
if (!/<head>[\s\S]*<!--PARAMS-->[\s\S]*<\/head>/.test(html)) fail('config/config-page.html needs ' + PARAMS_MARKER + ' inside <head>');
html = html.replace(MODULES_MARKER, () => bundle); // function: no $-pattern expansion

const out = '// GENERATED by tools/build-config.js from config/config-page.html - do not edit.\n' +
  'module.exports = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(path.join(root, 'src/pkjs/config-page.js'), out);
console.log('config page: ' + (html.length / 1024).toFixed(1) + ' KB html, module ' + (out.length / 1024).toFixed(1) + ' KB');
